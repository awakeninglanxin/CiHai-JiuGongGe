def build_prompt(code, name, node, desc=''):
    """根据代码特征自动构造图生提示词"""
    c = str(code)
    prompt_parts = []
    
    # 1前缀 + 法器
    if c[0] == '1' and code in WEAPON_MAP:
        weapon, wdesc = WEAPON_MAP[code]
        prompt_parts.append(f'手持{weapon} · {wdesc}')
    
    # 多6 + 水
    sixes = c.count('6')
    if sixes >= 2:
        prompt_parts.append(f'背景水元素: {water_elements(sixes)}')
    
    # 特定角色描述
    if code in ROLE_REFERENCES:
        prompt_parts.append(ROLE_REFERENCES[code])
    
    prompt = '，'.join(prompt_parts) if prompt_parts else desc
    return prompt


