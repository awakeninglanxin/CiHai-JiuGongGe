# ═══ 规则2: 多6代码 → 背景加水元素 ═══
def water_elements(sixes):
    """根据6的个数返回背景水元素描述"""
    if sixes >= 4: return '滔天巨浪 · 四海龙王围绕 · 瀑布深渊 · 汪洋大海'
    if sixes >= 3: return '奔腾江河 · 溪流环绕 · 水波荡漾 · 蓝色漩涡'
    if sixes >= 2: return '潺潺流水 · 细雨蒙蒙 · 露珠点点 · 湖水如镜'
    return ''

