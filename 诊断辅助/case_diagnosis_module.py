# ============ 诊断功能函数 ============
def get_main_soul_detail(main_soul):
    """获取主魂详细属性"""
    return MAIN_SOUL_DB.get(main_soul, {'错误': '主魂信息未找到'})

def get_deficiency_correction(deficiency_numbers):
    """获取缺格修正方案"""
    result = {'缺格诊断': {}, '喝B杯时间': {}}
    for num in deficiency_numbers:
        if num in DEFICIENCY_CORRECTION['缺格诊断']:
            result['缺格诊断'][num] = DEFICIENCY_CORRECTION['缺格诊断'][num]
        if num in DEFICIENCY_CORRECTION['喝B杯时间']:
            result['喝B杯时间'][num] = DEFICIENCY_CORRECTION['喝B杯时间'][num]
    return result

def get_relationship_analysis(yang_ge, yin_ge):
    """获取关系诊断分析"""
    return RELATIONSHIP_DIAGNOSIS

def generate_case_diagnosis_report(birth_info, yang_ge, yin_ge, yang_que, yin_que, main_soul):
    """生成个案诊断报告"""
    report = []
    
    report.append("# 九宫格个案诊断报告")
    report.append(f"**出生信息**: {birth_info}")
    report.append(f"**阳格**: {yang_ge} | **阴格**: {yin_ge}")
    report.append(f"**阳缺**: {yang_que} | **阴缺**: {yin_que}")
    report.append(f"**主魂**: {main_soul}")
    report.append("---")
    
    # 1. 主魂详细属性
    soul_detail = get_main_soul_detail(main_soul)
    report.append("## 一、主魂详细属性")
    for key, value in soul_detail.items():
        if value:
            report.append(f"**{key}**: {value}")
    report.append("")
    
    # 2. 缺格修正方案
    all_deficiencies = set(yang_que + yin_que)
    corrections = get_deficiency_correction(all_deficiencies)
    
    report.append("## 二、缺格修正方案")
    report.append("### A. 缺格诊断修正")
    for num, correction in corrections['缺格诊断'].items():
        report.append(f"- **缺{num}**: {correction}")
    
    report.append("### B. 喝B杯时间修正")
    for num, correction in corrections['喝B杯时间'].items():
        report.append(f"- **缺{num}**: {correction}")
    report.append("")
    
    # 3. 关系诊断
    relations = get_relationship_analysis(yang_ge, yin_ge)
    report.append("## 三、关系诊断")
    report.append("### 家庭关系")
    for key, value in relations['家庭关系'].items():
        report.append(f"- **{key}**: {value}")
    
    report.append("### 事业合伙人关系")
    for key, value in relations['事业合伙人关系'].items():
        report.append(f"- **{key}**: {value}")
    
    return '\n'.join(report)

