def append_fall_info(grid_info, yang_grid=None, yin_grid=None):
    """在已有九宫格信息后附加四清相关信息"""
    result = grid_info

    # 阴阳同格检测
    if yang_grid and yin_grid and str(yang_grid) == str(yin_grid):
        result += "\n\n" + get_fall_info("阴阳同格")

    # 特殊组合：阳1325+阴347
    if yang_grid == 1325 and yin_grid == 347:
        result += "\n\n" + get_fall_info("1325_347")

    # 添加四清总纲
    result += "\n\n" + get_fall_info("四清总纲")

    return result


